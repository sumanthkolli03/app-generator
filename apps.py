"""The app generator: turns each app's app.toml into the compose services, networks and Caddy
sites that run it, in generated/ (never edited by hand). Standard library only (Python 3.11+).

    apps.sh add <folder or .zip> --name N --kind K [--prefix P] [--prefix SITE=P] [--port 8080] [--health /healthz]
    apps.sh sync [--yes] [--build]    render, validate, show the change, apply, wait for health
    apps.sh check                     render and validate into generated/.next; change nothing
    apps.sh list
    apps.sh remove <name>

An app is a folder under backend/public-apps/ with an app.toml and a whitelist.txt. Its sites are
<prefix>.<PUBLIC_DOMAIN> (or the apex), named in .env, never in the repo. Every public service gets
the same hardening, which no app.toml can turn off. Kinds so far: static and rw (auth = "self").
"""
