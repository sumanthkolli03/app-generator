# ---------------------------------------------------------------- .env and the base compose file

def read_env():
    """.env as {name: value}. Values are used, never printed."""
    out = {}
    try:
        text = (ROOT / ".env").read_text(encoding="utf-8")
    except OSError:
        raise Problem(f"no .env in {ROOT}")
    for line in text.splitlines():
        line = line.strip().rstrip("\r")
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def env_append(name, value):
    """Adds NAME=value to .env, after a line break if the file ends without one."""
    p = ROOT / ".env"
    data = p.read_bytes()
    crlf = b"\r\n" in data
    nl = b"\r\n" if crlf else b"\n"
    if data and not data.endswith(b"\n"):
        data += nl
    p.write_bytes(data + f"{name}={value}".encode() + nl)


def compose(*args, files=None, check=True, capture=True):
    """docker compose in the project folder. files=None: whatever .env's COMPOSE_FILE says
    (never pass -f with up: with --remove-orphans it would remove every app)."""
    cmd = ["docker", "compose"]
    for f in files or []:
        cmd += ["-f", str(f)]
    r = subprocess.run(cmd + list(args), cwd=ROOT, text=True, capture_output=capture)
    if check and r.returncode:
        raise Problem(f"docker compose {' '.join(args)} failed:\n{(r.stderr or r.stdout or '').strip()}")
    return r


def merged(apps_file):
    """The merged compose config (JSON) of the base file plus a generated file."""
    files = [ROOT / "docker-compose.yml"] + ([apps_file] if apps_file and apps_file.exists() else [])
    return json.loads(compose("config", "--format", "json", files=files).stdout)


# ---------------------------------------------------------------- reading and checking an app

def stack_dir(name):
    return APPS / name


def site_var(app, key, site):
    """The .env name holding a site's address: PUBLIC_DOMAIN for the apex, else <APP>[_<SITE>]_DOMAIN."""
    if site.get("apex"):
        return "PUBLIC_DOMAIN"
    up = app.replace("-", "_").upper()
    return f"{up}_DOMAIN" if key == "main" else f"{up}_{key.upper()}_DOMAIN"


def container(app, svc, single):
    return app if single else f"{app}-{svc}"


def _keys(where, table, allowed):
    if not isinstance(table, dict):
        raise Problem(f"{where}: must be a table")
    extra = set(table) - allowed
    if extra:
        raise Problem(f"{where}: unknown key(s) {', '.join(sorted(extra))} (allowed: {', '.join(sorted(allowed))})")


def _str_map(where, m, keyre, valcheck):
    if not isinstance(m, dict):
        raise Problem(f"{where}: must be a table")
    for k, v in m.items():
        if not keyre.fullmatch(k):
            raise Problem(f"{where}: bad name {k!r}")
        if not isinstance(v, str) or not valcheck(v):
            raise Problem(f"{where}.{k}: bad value")
    return m


def _header_value(v):
    return "\n" not in v and "\r" not in v and "{" not in v and "}" not in v and len(v) < 2000


def whitelist(folder):
    """The hosts in whitelist.txt (comments and blank lines dropped). None if the file is missing."""
    p = folder / "whitelist.txt"
    if not p.is_file():
        return None
    hosts = []
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            hosts.append(line)
    return hosts


def load(folder):
    """Reads and checks one app. Returns a dict with everything rendering needs."""
    name = folder.name
    where = f"{STACK}-apps/{name}/app.toml"
    if not NAME.fullmatch(name) or "--" in name or name in RESERVED or name.startswith(("wg-", "caddy-")):
        raise Problem(f"{name}: app names are [a-z][a-z0-9-], 2-31 long, not reserved ({', '.join(sorted(RESERVED))})")
    try:
        cfg = tomllib.loads((folder / "app.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise Problem(f"{where}: {e}")
    _keys(where, cfg, APP_KEYS)
    kind = cfg.get("kind")
    if kind not in KINDS:
        raise Problem(f"{where}: kind must be one of {', '.join(sorted(KINDS))}")
    if kind not in READY:
        raise Problem(f"{where}: kind {kind!r} isn't built yet (so far: {', '.join(sorted(READY))})")
    auth = cfg.get("auth", "authelia" if kind == "rw" else None)
    if kind == "rw" and auth != "self":
        raise Problem(f"{where}: rw apps behind the Authelia sign-in come in a later stage; "
                      f"auth = \"self\" is for apps that sign people in themselves")
    if kind != "rw" and "auth" in cfg:
        raise Problem(f"{where}: auth is for rw apps only")
    origin = cfg.get("origin_check", kind in ("live", "rw"))
    if not isinstance(origin, bool) or (origin and kind == "static"):
        raise Problem(f"{where}: origin_check is true or false, and static apps take no writes")
    hosts = whitelist(folder)
    if hosts is None:
        raise Problem(f"{STACK}-apps/{name}: whitelist.txt is missing (an empty one means it never goes out)")
    if hosts:
        raise Problem(f"{STACK}-apps/{name}/whitelist.txt lists hosts, but going out arrives in a later stage")

    services = cfg.get("services")
    if not isinstance(services, dict) or not services:
        raise Problem(f"{where}: needs at least one [services.<name>]")
    single = len(services) == 1
    svcs = {}
    for key, s in services.items():
        w = f"{where} [services.{key}]"
        if not KEY.fullmatch(key):
            raise Problem(f"{w}: service names are [a-z][a-z0-9], up to 16")
        _keys(w, s, SERVICE_KEYS)
        if ("image" in s) == ("build" in s):
            raise Problem(f"{w}: give exactly one of build (a folder) or image")
        if "build" in s and (not isinstance(s["build"], str) or not (s["build"] == "." or REL.fullmatch(s["build"]))
                             or ".." in s["build"].split("/") or not (folder / s["build"] / "Dockerfile").is_file()):
            raise Problem(f"{w}: build must be a folder of the app holding a Dockerfile")
        if "image" in s and not re.fullmatch(r"[a-z0-9][a-z0-9._/-]*(:[A-Za-z0-9._-]+)?(@sha256:[0-9a-f]{64})?", str(s["image"])):
            raise Problem(f"{w}: bad image name")
        user = s.get("user", "puid")
        if user not in ("puid", "image"):
            raise Problem(f"{w}: user is \"puid\" (PUID:PGID) or \"image\" (the image's own non-root user)")
        net = s.get("network")
        if net not in (None, "none"):
            raise Problem(f"{w}: network can only be \"none\"")
        mounts = []
        for i, m in enumerate(s.get("mounts", [])):
            mw = f"{w} mounts[{i}]"
            if not isinstance(m, dict):
                raise Problem(f"{mw}: must be a table like {{ shared = \"x\", at = \"/data/x\" }}")
            _keys(mw, m, {"backend", "data", "shared", "at", "ro"})
            src = [k for k in ("backend", "data", "shared") if k in m]
            if len(src) != 1:
                raise Problem(f"{mw}: give exactly one of backend, data, shared")
            what, rel, at = src[0], m[src[0]], m.get("at")
            if not isinstance(rel, str) or not REL.fullmatch(rel) or ".." in rel.split("/"):
                raise Problem(f"{mw}: {what} must be a relative path inside the app's folder")
            if not isinstance(at, str) or not at.startswith("/") or at == "/" or ".." in at.split("/") \
                    or any(at == f or at.startswith(f + "/") for f in FORBIDDEN_AT) or not PATH.fullmatch(at):
                raise Problem(f"{mw}: at must be an absolute path in the container (not /, /proc, /sys, /dev or the socket)")
            if what == "backend" and not (folder / rel).exists():
                raise Problem(f"{mw}: backend/{STACK}-apps/{name}/{rel} doesn't exist")
            if kind == "static" and what != "backend":
                raise Problem(f"{mw}: static apps store nothing (no data or shared folders)")
            ro = True if what == "backend" else bool(m.get("ro", False))
            mounts.append((what, rel, at, ro))
        health = s.get("health")
        if not isinstance(health, dict):
            raise Problem(f"{w}: needs a [services.{key}.health] with test = [\"CMD\", ...]")
        _keys(f"{w}.health", health, HEALTH_KEYS)
        test = health.get("test")
        if not (isinstance(test, list) and test and test[0] in ("CMD", "CMD-SHELL") and all(isinstance(x, str) for x in test)):
            raise Problem(f"{w}.health: test is a list starting with \"CMD\" or \"CMD-SHELL\"")
        for k in ("interval", "timeout", "start_period"):
            if k in health and not (isinstance(health[k], str) and DURATION.fullmatch(health[k])):
                raise Problem(f"{w}.health: {k} like \"30s\"")
        if "retries" in health and not (isinstance(health["retries"], int) and 0 < health["retries"] < 100):
            raise Problem(f"{w}.health: retries is a small number")
        for k in ("memory", "tmp"):
            if k in s and not (isinstance(s[k], str) and SIZE.fullmatch(s[k])):
                raise Problem(f"{w}: {k} like \"512m\"")
        if "cpus" in s and not (isinstance(s["cpus"], (int, float)) and 0 < s["cpus"] <= 64):
            raise Problem(f"{w}: cpus is a number")
        if "pids" in s and not (isinstance(s["pids"], int) and 8 <= s["pids"] <= 4096):
            raise Problem(f"{w}: pids is a number")
        tmpfs = []
        for t in s.get("tmpfs", []):
            if not (isinstance(t, str) and re.fullmatch(r"(/[A-Za-z0-9._-]+)+:\d+[kmg]", t)) or t.split(":")[0] == "/tmp":
                raise Problem(f"{w}: tmpfs entries look like \"/var/cache/nginx:32m\" (/tmp is set by tmp)")
            tmpfs.append(t)
        env = _str_map(f"{w}.env", s.get("env", {}), re.compile(r"[A-Z_][A-Z0-9_]*"), lambda v: "\n" not in v)
        args = _str_map(f"{w}.build_args", s.get("build_args", {}), re.compile(r"[A-Za-z_][A-Za-z0-9_]*"), lambda v: "\n" not in v)
        logs = s.get("logs", kind != "static")
        if not isinstance(logs, bool):
            raise Problem(f"{w}: logs is true or false")
        svcs[key] = dict(s, user=user, network=net, mounts=mounts, health=health, tmpfs=tmpfs, env=env,
                         build_args=args, logs=logs, container=container(name, key, single))

    sites = cfg.get("sites")
    if not isinstance(sites, dict) or not sites:
        raise Problem(f"{where}: needs at least one [sites.<name>] (every web kind has a site)")
    if "main" not in sites:
        raise Problem(f"{where}: one site must be called main")
    targets = set()
    out_sites = {}
    for key, site in sites.items():
        w = f"{where} [sites.{key}]"
        if not KEY.fullmatch(key):
            raise Problem(f"{w}: site names are [a-z][a-z0-9], up to 16")
        _keys(w, site, SITE_KEYS)
        if site.get("apex") and key != "main":
            raise Problem(f"{w}: only the main site can be the apex")
        hdrs = _str_map(f"{w}.headers", site.get("headers", {}), HEADER, _header_value)
        routes = site.get("routes")
        if not isinstance(routes, list) or not routes:
            raise Problem(f"{w}: needs routes = [{{ to = \"service:port\" }}]")
        rs = []
        for i, r in enumerate(routes):
            rw = f"{w} routes[{i}]"
            _keys(rw, r, ROUTE_KEYS)
            paths = r.get("paths", [])
            if not isinstance(paths, list) or not all(isinstance(p, str) and PATH.fullmatch(p) for p in paths):
                raise Problem(f"{rw}: paths are like \"/\", \"/api/*\"")
            if paths in ([], ["/*"], ["*"]):
                paths = []
            if not paths and i != len(routes) - 1:
                raise Problem(f"{rw}: a route without paths takes everything, so it must come last")
            to = r.get("to")
            m = re.fullmatch(r"([a-z][a-z0-9]{0,15})?:(\d{1,5})", to) if isinstance(to, str) else None
            if not m:
                raise Problem(f"{rw}: to is \"service:port\" (or \":port\" for an app with one service)")
            svc = m[1] or (next(iter(svcs)) if single else None)
            if svc not in svcs:
                raise Problem(f"{rw}: no service {m[1]!r}")
            if svcs[svc]["network"] == "none":
                raise Problem(f"{rw}: {svc} has no network, so nothing can reach it")
            mb = r.get("max_body")
            if mb is not None and not (isinstance(mb, str) and SIZE.fullmatch(mb)):
                raise Problem(f"{rw}: max_body like \"5100MB\"")
            rh = _str_map(f"{rw}.headers", r.get("headers", {}), HEADER, _header_value)
            targets.add(svc)
            rs.append({"paths": paths, "svc": svc, "port": int(m[2]), "max_body": mb, "encode": bool(r.get("encode", False)), "headers": rh})
        out_sites[key] = {"apex": bool(site.get("apex")), "encode": bool(site.get("encode", kind == "static")),
                          "headers": hdrs, "routes": rs, "var": site_var(name, key, site)}
    for key, s in svcs.items():
        if key not in targets and s["network"] != "none":
            raise Problem(f"{where} [services.{key}]: no route reaches it, so it must have network = \"none\" "
                          f"(otherwise Docker would put it on a network with internet access)")
    if kind == "rw" and not any(m[0] in ("data", "shared") for s in svcs.values() for m in s["mounts"]):
        raise Problem(f"{where}: an rw app stores what visitors send: mount a data or shared folder")
    return {"name": name, "kind": kind, "auth": auth, "origin": origin, "sites": out_sites, "services": svcs,
            "single": single, "folder": folder}


def load_all(env, base_services):
    """Every app with an app.toml, checked one by one and then against each other."""
    apps = []
    for folder in sorted(p for p in APPS.glob("*") if p.is_dir() and (p / "app.toml").is_file()):
        apps.append(load(folder))
    pub = env.get("PUBLIC_DOMAIN")
    if apps and not pub:
        raise Problem(".env has no PUBLIC_DOMAIN")
    taken, names, apex = {}, set(base_services), None
    reserved = {env.get(k) for k in ("PRIVATE_DOMAIN", "PRIVATE_AUTH_DOMAIN") if env.get(k)} | {f"www.{pub}"}
    for a in apps:
        for s in a["services"].values():
            for n in (s["container"], f"{s['container']}_net"):
                if n in names:
                    raise Problem(f"{a['name']}: the name {n} is already used")
                names.add(n)
        for key, site in a["sites"].items():
            var = site["var"]
            if site["apex"]:
                if apex:
                    raise Problem(f"{a['name']}: {apex} already has the apex")
                apex = a["name"]
                continue
            value = env.get(var)
            if not value:
                raise Problem(f"{a['name']}: .env has no {var} (add the app with --prefix, or write {var}=<label>.{pub} into .env)")
            if not (value.endswith("." + pub) and LABEL.fullmatch(value[: -len(pub) - 1])):
                raise Problem(f"{a['name']}: {var} must be one label under PUBLIC_DOMAIN, like x.{pub}")
            if value in reserved or value in taken:
                raise Problem(f"{a['name']}: {var} is the same address as {taken.get(value, 'a reserved name')}")
            taken[value] = var
    return apps


# ---------------------------------------------------------------- rendering: compose

def _value(app, v):
    """site:<key> -> that site's .env name; env:<NAME> -> a .env value; anything else literally."""
    if v.startswith("site:"):
        site = app["sites"].get(v[5:])
        if not site:
            raise Problem(f"{app['name']}: no site {v[5:]!r} for {v}")
        return Interp(f"${{{site['var']}:?set {site['var']} in .env}}")
    if v.startswith("env:"):
        n = v[4:]
        if not re.fullmatch(r"[A-Z_][A-Z0-9_]*", n):
            raise Problem(f"{app['name']}: bad {v}")
        return Interp(f"${{{n}:?set {n} in .env}}")
    return v


def service(app, key, s):
    name, c = app["name"], s["container"]
    base = f"./backend/{STACK}-apps/{name}"
    d = {}
    if "image" in s:
        d["image"] = s["image"]
    else:
        b = {"context": base if s["build"] == "." else f"{base}/{s['build']}"}
        if s["build_args"]:
            b["args"] = {k: _value(app, v) for k, v in s["build_args"].items()}
        d["build"] = b
        d["image"] = f"{c}:local"
    d["container_name"] = c
    d["restart"] = "unless-stopped"
    if s["user"] == "puid":
        d["user"] = Interp("${PUID:-1000}:${PGID:-1000}")
    if s["network"] == "none":
        d["network_mode"] = "none"
    else:
        d["networks"] = [f"{c}_net"]
    d["read_only"] = True
    d["cap_drop"] = ["ALL"]
    d["security_opt"] = ["no-new-privileges:true"]
    d["tmpfs"] = [f"/tmp:size={s.get('tmp', DEFAULTS['tmp'])},mode=1777"] + \
                 [f"{t.split(':')[0]}:size={t.split(':')[1]},mode=1777" for t in s["tmpfs"]]
    if s["env"]:
        d["environment"] = {k: _value(app, v) for k, v in s["env"].items()}
    vols = []
    for what, rel, at, ro in s["mounts"]:
        src = {"backend": base, "data": f"./internal-config/{STACK}-apps/{name}", "shared": f"./shared-files/{name}"}[what]
        vols.append(f"{src}/{rel}:{at}" + (":ro" if ro else ""))
    if s["logs"]:
        vols.append(f"./logs/{STACK}-apps/{name}/app{'' if app['single'] else '/' + key}:/logs")
    if vols:
        d["volumes"] = vols
    d["mem_limit"] = s.get("memory", DEFAULTS["memory"])
    d["cpus"] = s.get("cpus", DEFAULTS["cpus"])
    d["pids_limit"] = s.get("pids", DEFAULTS["pids"])
    h = s["health"]
    d["healthcheck"] = {"test": h["test"], "interval": h.get("interval", "30s"), "timeout": h.get("timeout", "5s"),
                        "retries": h.get("retries", 3), "start_period": h.get("start_period", "10s")}
    d["logging"] = LOGGING
    return d


def compose_doc(apps):
    services, networks, wg_nets, caddy_env, caddy_vols = {}, {}, {}, {}, []
    for a in apps:
        for site in a["sites"].values():
            if not site["apex"]:
                caddy_env[site["var"]] = Interp(f"${{{site['var']}:?set {site['var']} in .env}}")
        caddy_vols.append(f"./logs/{STACK}-apps/{a['name']}/access:/logs/{STACK}-apps/{a['name']}/access")
        for key, s in a["services"].items():
            services[s["container"]] = service(a, key, s)
            if s["network"] != "none":
                net = f"{s['container']}_net"
                networks[net] = {"internal": True}
                wg_nets[net] = {}
    head = {}
    if wg_nets:
        head["wg-public"] = {"networks": wg_nets}
    if caddy_env or caddy_vols:
        head["caddy-public"] = {k: v for k, v in (("environment", caddy_env), ("volumes", caddy_vols)) if v}
    doc = {"services": head | services}
    if networks:
        doc["networks"] = networks
    return doc


def _scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v) if isinstance(v, Interp) else str(v).replace("$", "$$"), ensure_ascii=False)


def yaml(obj, ind=0):
    """Plain YAML for dicts, lists and scalars; every string double-quoted (JSON rules are valid YAML)."""
    pad, out = "  " * ind, []
    items = obj.items() if isinstance(obj, dict) else ((None, v) for v in obj)
    for k, v in items:
        lead = f"{pad}{k if re.fullmatch(r'[A-Za-z0-9_.-]+', k) else json.dumps(k)}:" if k is not None else f"{pad}-"
        if isinstance(v, (dict, list)) and v:
            sub = yaml(v, ind + 1)
            if k is None:
                out.append(f"{lead} {sub[0].lstrip()}")
                out += sub[1:]
            else:
                out.append(lead)
                out += sub
        else:
            out.append(f"{lead} {('{}' if isinstance(v, dict) else '[]') if isinstance(v, (dict, list)) else _scalar(v)}")
    return out


# ---------------------------------------------------------------- rendering: Caddy

def _q(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _origin_lines(var, pad):
    """Writes and websocket upgrades from another site's page get 403; requests without an Origin
    (curl, ShareX, other servers) pass: a browser always sends one on these."""
    return [f"{pad}@foreign_write {{", f"{pad}    not method GET HEAD", f"{pad}    header Origin *",
            f"{pad}    not header Origin https://{{${var}}}", f"{pad}}}", f"{pad}respond @foreign_write \"Forbidden\" 403",
            f"{pad}@foreign_ws {{", f"{pad}    header Upgrade *", f"{pad}    header Origin *",
            f"{pad}    not header Origin https://{{${var}}}", f"{pad}}}", f"{pad}respond @foreign_ws \"Forbidden\" 403"]


def _route_body(app, site, r, pad):
    out = []
    if r["max_body"]:
        out += [f"{pad}request_body {{", f"{pad}    max_size {r['max_body']}", f"{pad}}}"]
    if r["encode"]:
        out.append(f"{pad}encode zstd gzip")
    for h, v in r["headers"].items():
        out.append(f"{pad}header {h} {_q(v)}")
    if app["origin"]:
        out += _origin_lines(site["var"], pad)
    c = app["services"][r["svc"]]["container"]
    out += [f"{pad}reverse_proxy {c}:{r['port']} {{", f"{pad}    header_up X-Real-IP {{remote_host}}", f"{pad}}}"]
    return out


def caddy_doc(app):
    name = app["name"]
    out = [f"# Generated by generator/apps.sh from backend/{STACK}-apps/{name}/app.toml. Don't edit: run  bash generator/apps.sh sync"]
    for key, site in app["sites"].items():
        var = site["var"]
        if site["apex"]:
            out += ["", f"www.{{${var}}} {{", f"    redir https://{{${var}}}{{uri}}", "}"]
        logfile = "access.log" if key == "main" else f"{key}-access.log"
        out += ["", f"{{${var}}} {{", "    log {", f"        output file /logs/{STACK}-apps/{name}/access/{logfile} {{",
                "            roll_size 20mb", "            roll_keep 100000", "            roll_keep_for 36500d",
                "        }", "        format json", "    }"]
        if site["encode"]:
            out.append("    encode zstd gzip")
        out.append("    header {")
        for h, v in BASE_HEADERS + list(site["headers"].items()):
            out.append(f"        {h}" if v is None else f"        {h} {_q(v)}")
        out.append("    }")
        routes = site["routes"]
        if len(routes) == 1 and not routes[0]["paths"]:
            out += _route_body(app, site, routes[0], "    ")
        else:
            for i, r in enumerate(routes, 1):
                if r["paths"]:
                    out += [f"    @r{i} path {' '.join(r['paths'])}", f"    handle @r{i} {{"] + _route_body(app, site, r, "        ") + ["    }"]
                else:
                    out += ["    handle {"] + _route_body(app, site, r, "        ") + ["    }"]
            if routes[-1]["paths"]:
                out += ["    handle {", "        respond 404", "    }"]
        out.append("}")
    return "\n".join(out) + "\n"


def render(apps, into):
    """Writes the whole generated set into a fresh folder."""
    if into.exists():
        shutil.rmtree(into)
    (into / "caddy-public").mkdir(parents=True)
    (into / "docker-compose.apps.yml").write_text(GENERATED.format(stack=STACK) + "\n".join(yaml(compose_doc(apps))) + "\n", encoding="utf-8")
    for a in apps:
        (into / "caddy-public" / f"{a['name']}.caddy").write_text(caddy_doc(a), encoding="utf-8")


# ---------------------------------------------------------------- validating the rendered set

def caddy_validate(next_dir, env):
    """Validates caddy-public's Caddyfile with the rendered sites: the caddy image, or $CADDY_BIN."""
    caddyfile = ROOT / "backend" / "caddy" / "caddy-public" / "Caddyfile"
    GEN.mkdir(parents=True, exist_ok=True)               # inside the project, so Docker can mount it
    with tempfile.TemporaryDirectory(dir=GEN, prefix=".validate-") as t:
        shutil.copy(caddyfile, Path(t) / "Caddyfile")
        shutil.copytree(next_dir / "caddy-public", Path(t) / "apps")
        if os.environ.get("CADDY_BIN"):
            r = subprocess.run([os.environ["CADDY_BIN"], "validate", "--adapter", "caddyfile", "--config", f"{t}/Caddyfile"],
                               env=dict(os.environ, **env), text=True, capture_output=True)
        else:
            cmd = ["docker", "run", "--rm", "--network", "none", "-v", f"{t}:/etc/caddy:ro"]
            for k, v in env.items():
                cmd += ["-e", f"{k}={v}"]
            r = subprocess.run(cmd + ["caddy:latest", "caddy", "validate", "--adapter", "caddyfile", "--config", "/etc/caddy/Caddyfile"],
                               text=True, capture_output=True)
    if r.returncode:
        raise Problem("Caddy refuses the rendered sites:\n" + (r.stderr or r.stdout).strip()[-2000:])


def _env_of(svc):
    e = svc.get("environment") or {}
    return {k: v for k, v in e.items() if v is not None} if isinstance(e, dict) else dict(x.split("=", 1) for x in e)


def prepare(env):
    """Loads every app, renders into generated/.next and validates it. Returns (apps, next_dir, current, nxt)."""
    if not (ROOT / "docker-compose.yml").is_file():
        raise Problem(f"{ROOT} has no docker-compose.yml (set APPS_ROOT to the server folder)")
    base = json.loads(compose("config", "--format", "json", files=[ROOT / "docker-compose.yml"]).stdout)
    for need in ("wg-public", "caddy-public"):
        if need not in base["services"]:
            raise Problem(f"docker-compose.yml has no {need}")
    apps = load_all(env, base["services"].keys() | base.get("networks", {}).keys())
    nxt_dir = GEN / ".next"
    render(apps, nxt_dir)
    current = merged(GEN / "docker-compose.apps.yml")
    nxt = merged(nxt_dir / "docker-compose.apps.yml")
    caddy_validate(nxt_dir, _env_of(nxt["services"]["caddy-public"]))
    # nothing but the public tunnel, its Caddy and the apps may change
    ours = {s["container"] for a in apps for s in a["services"].values()} | {"wg-public", "caddy-public"}
    old_apps = set(current["services"]) - set(base["services"])
    for svc in set(current["services"]) | set(nxt["services"]):
        if svc in ours or svc in old_apps:
            continue
        if current["services"].get(svc) != nxt["services"].get(svc):
            raise Problem(f"the rendered set would change {svc}, which isn't the generator's to touch")
    return apps, nxt_dir, current, nxt


def changes(nxt_dir):
    """Unified diffs between generated/ and generated/.next, file by file."""
    out = []
    names = {p.relative_to(nxt_dir) for p in nxt_dir.rglob("*") if p.is_file()} | \
            {p.relative_to(GEN) for p in GEN.rglob("*") if p.is_file() and not p.relative_to(GEN).parts[0].startswith(".")}
    for rel in sorted(names, key=str):
        a, b = GEN / rel, nxt_dir / rel
        old = a.read_text(encoding="utf-8").splitlines(keepends=True) if a.exists() else []
        new = b.read_text(encoding="utf-8").splitlines(keepends=True) if b.exists() else []
        if old != new:
            out.append("".join(difflib.unified_diff(old, new, f"generated/{rel}", f"generated/{rel} (new)")))
    return out


# ---------------------------------------------------------------- applying

def _swap(src, dst):
    """Replaces dst's generated files with src's. Dot folders (.next, .previous, .failed) stay put."""
    dst.mkdir(parents=True, exist_ok=True)
    for p in list(dst.iterdir()):
        if not p.name.startswith("."):
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    for p in list(src.iterdir()):
        if not p.name.startswith("."):
            shutil.move(str(p), str(dst / p.name))


def folders(apps):
    """Creates every folder the apps mount, so Docker never makes them (as root)."""
    for a in apps:
        n = a["name"]
        (ROOT / "logs" / f"{STACK}-apps" / n / "access").mkdir(parents=True, exist_ok=True)
        for key, s in a["services"].items():
            if s["logs"]:
                (ROOT / "logs" / f"{STACK}-apps" / n / "app" / ("" if a["single"] else key)).mkdir(parents=True, exist_ok=True)
            for what, rel, at, ro in s["mounts"]:
                if what == "data":
                    (ROOT / "internal-config" / f"{STACK}-apps" / n / rel).mkdir(parents=True, exist_ok=True)
                elif what == "shared":
                    (ROOT / "shared-files" / n / rel).mkdir(parents=True, exist_ok=True)


def wait_healthy(apps, seconds=240):
    names = [s["container"] for a in apps for s in a["services"].values()]
    deadline, last = time.time() + seconds, {}
    while time.time() < deadline:
        r = subprocess.run(["docker", "inspect", "-f", "{{.Name}} {{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{end}}"] + names,
                           text=True, capture_output=True)
        last = {ln.split()[0].lstrip("/"): ln.split()[1:] for ln in r.stdout.splitlines() if ln.strip()}
        if all(last.get(n, [""])[-1] == "healthy" for n in names):
            return []
        if any(st and st[0] in ("exited", "dead") for st in last.values()):
            break
        time.sleep(5)
    return [f"{n}: {' '.join(last.get(n, ['missing']))}" for n in names if last.get(n, [""])[-1] != "healthy"]


def run_up(build):
    say("+ docker compose up -d --remove-orphans" + (" --build" if build else ""))
    compose("up", "-d", "--remove-orphans", *(["--build"] if build else []), capture=False)
    say("+ docker compose up -d --force-recreate caddy-public    (it shares wg-public's network namespace)")
    compose("up", "-d", "--force-recreate", "caddy-public", capture=False)


def cmd_check(args):
    env = read_env()
    apps, nxt_dir, _, _ = prepare(env)
    diffs = changes(nxt_dir)
    say(f"{len(apps)} app(s) valid: {', '.join(a['name'] for a in apps) or 'none'}")
    say("\n".join(diffs) if diffs else "generated/ is up to date")
    return 0


def cmd_sync(args):
    env = read_env()
    if env.get("COMPOSE_FILE", "").split(":") != ["docker-compose.yml", "generated/docker-compose.apps.yml"]:
        raise Problem("put this line into .env first:  COMPOSE_FILE=docker-compose.yml:generated/docker-compose.apps.yml")
    apps, nxt_dir, current, nxt = prepare(env)
    diffs = changes(nxt_dir)
    if not diffs and not args.build and not args.force:
        shutil.rmtree(nxt_dir)
        say("nothing to change")
        return 0
    say("\n".join(diffs) if diffs else "(no file changes)")
    gone = sorted(set(current["services"]) - set(nxt["services"]))
    say(f"\nApplying recreates whatever changed, and always caddy-public: public sites blink for a few seconds"
        + (f". It REMOVES {', '.join(gone)}" if gone else "") + ".")
    if not args.yes and not ask("apply? [y/N] "):
        shutil.rmtree(nxt_dir)
        say("nothing changed")
        return 1
    prev = GEN / ".previous"
    if prev.exists():
        shutil.rmtree(prev)
    prev.mkdir(parents=True)
    _swap(GEN, prev)
    _swap(nxt_dir, GEN)
    shutil.rmtree(nxt_dir)
    folders(apps)
    try:
        run_up(args.build)
        bad = wait_healthy(apps)
        roots = [s["container"] for a in apps for s in a["services"].values() if s["user"] == "image"]
        for c in roots:
            u = subprocess.run(["docker", "inspect", "-f", "{{.Config.User}}", c], text=True, capture_output=True).stdout.strip()
            if u in ("", "0", "root") or u.startswith(("0:", "root:")):
                bad.append(f"{c}: its image runs as root; use user = \"puid\"")
        if bad:
            raise Problem("not healthy:\n  " + "\n  ".join(bad))
    except Problem as e:
        say(f"\nFAILED: {e}\nputting the previous generated/ back")
        failed = GEN / ".failed"
        shutil.rmtree(failed, ignore_errors=True)
        _swap(GEN, failed)
        _swap(prev, GEN)
        try:
            run_up(False)
        except Problem as e2:
            say(f"and that failed too: {e2}")
        say("the failed set is in generated/.failed")
        return 1
    say("\nall apps healthy: " + ", ".join(s["container"] for a in apps for s in a["services"].values()))
    return 0


def cmd_list(args):
    env = read_env()
    for folder in sorted(p for p in APPS.glob("*") if p.is_dir()):
        try:
            a = load(folder)
        except Problem as e:
            say(f"{folder.name:16} -- {e}" if (folder / "app.toml").exists() else f"{folder.name:16} -- not added (no app.toml)")
            continue
        sites = ", ".join(env.get(s["var"], f"<{s['var']} missing>") for s in a["sites"].values())
        say(f"{a['name']:16} {a['kind']:7} {sites}")
        for s in a["services"].values():
            say(f"{'':16}   {s['container']:20} {'no network' if s['network'] == 'none' else 'reached by Caddy'}; goes out: never")
    return 0


def _unpack(src, dest):
    """Copies a folder or a zip into dest. A zip with one top folder is unwrapped. No links, no escapes."""
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        if src.is_file() and zipfile.is_zipfile(src):
            with zipfile.ZipFile(src) as z:
                for info in z.infolist():
                    p = Path(info.filename)
                    if p.is_absolute() or ".." in p.parts or (info.external_attr >> 16) & 0o170000 == 0o120000:
                        raise Problem(f"{src}: refusing {info.filename} (absolute, .. or a link)")
                z.extractall(t / "x")
            top = list((t / "x").iterdir())
            root = top[0] if len(top) == 1 and top[0].is_dir() else t / "x"
        elif src.is_dir():
            root = src
        else:
            raise Problem(f"{src}: not a folder or a zip")
        for p in root.rglob("*"):
            if p.is_symlink():
                raise Problem(f"{p}: refusing links")
        shutil.copytree(root, dest)


def cmd_add(args):
    env = read_env()
    name, kind = args.name, args.kind
    if kind not in READY:
        raise Problem(f"kind {kind!r} isn't built yet (so far: {', '.join(sorted(READY))})")
    dest = stack_dir(name)
    src = Path(args.source).resolve()
    if src != dest.resolve():
        if dest.exists():
            raise Problem(f"backend/{STACK}-apps/{name} already exists")
        _unpack(src, dest)
        say(f"copied into backend/{STACK}-apps/{name}")
    if (dest / "app.toml.removed").exists() and not (dest / "app.toml").exists():
        (dest / "app.toml.removed").rename(dest / "app.toml")
    prefixes = {}
    for p in args.prefix or []:
        site, _, label = p.rpartition("=")
        prefixes[site or "main"] = label
    if not (dest / "app.toml").exists():
        if not (dest / "Dockerfile").is_file():
            raise Problem(f"backend/{STACK}-apps/{name} has neither an app.toml nor a Dockerfile")
        (dest / "app.toml").write_text(starter(kind, prefixes.get("main") == "@", args.port, args.health), encoding="utf-8")
        say(f"wrote backend/{STACK}-apps/{name}/app.toml (edit it, then sync, to change limits, headers or routes)")
    if not (dest / "whitelist.txt").exists():
        (dest / "whitelist.txt").write_text("# Hosts this app may connect to, one per line. Nothing listed: it never goes out.\n", encoding="utf-8")
    app = load(dest)
    if app["kind"] != kind:
        raise Problem(f"app.toml says kind = {app['kind']!r}, not {kind!r}")
    pub = env.get("PUBLIC_DOMAIN") or ""
    for key, site in app["sites"].items():
        label = prefixes.pop(key, None)
        if site["apex"]:
            if label not in (None, "@"):
                raise Problem(f"site {key} is the apex in app.toml: use --prefix @ or leave it out")
            continue
        if label == "@":
            raise Problem(f"site {key}: --prefix @ means the apex; set apex = true in app.toml for that")
        have = env.get(site["var"])
        if label is None:
            if not have:
                raise Problem(f"give the site's label: --prefix {'' if key == 'main' else key + '='}<label>  (the site becomes <label>.PUBLIC_DOMAIN)")
            continue
        if not LABEL.fullmatch(label):
            raise Problem(f"--prefix {label!r}: one DNS label, a-z 0-9 and -")
        want = f"{label}.{pub}"
        if have and have != want:
            raise Problem(f".env already has {site['var']} with a different address; change .env by hand if you mean it")
        if not have:
            env_append(site["var"], want)
            env[site["var"]] = want
            say(f"added {site['var']} to .env")
    if prefixes:
        raise Problem(f"no site(s) {', '.join(prefixes)} in app.toml")
    if any(m[0] == "shared" for s in app["services"].values() for m in s["mounts"]):
        say(f"note: shared-files/{name}/ is also visible in copyparty's /files to whoever can read [/]; "
            f"give it its own volume in copyparty.conf if they shouldn't")
    return cmd_sync(args)


def starter(kind, apex, port, health):
    """An app.toml for a one-container app added from flags."""
    return f"""# Read by the generator. After editing: bash generator/apps.sh sync
kind = "{kind}"

[sites.main]{'''
apex = true''' if apex else ""}
routes = [{{ to = ":{port}" }}]

[services.app]
build = "."
# memory = "512m"      # the defaults: memory 512m, cpus 4, pids 128, tmp 16m
[services.app.health]
test = ["CMD", "wget", "-qO-", "http://127.0.0.1:{port}{health}"]   # an image without wget needs another command
"""


def cmd_remove(args):
    p = stack_dir(args.name) / "app.toml"
    if not p.exists():
        raise Problem(f"{args.name} isn't an app (no backend/{STACK}-apps/{args.name}/app.toml)")
    if not args.yes and not ask(f"stop and remove {args.name}? Its folder, data and logs stay. [y/N] "):
        return 1
    p.rename(p.with_name("app.toml.removed"))
    say(f"renamed its app.toml to app.toml.removed (add it again to bring it back)")
    args.yes = True
    return cmd_sync(args)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="apps.sh", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add", help="add an app from a folder or a zip, then sync")
    a.add_argument("source")
    a.add_argument("--name", required=True)
    a.add_argument("--kind", required=True, choices=sorted(KINDS))
    a.add_argument("--prefix", action="append", help="the main site's label, @ for the apex, or SITE=label")
    a.add_argument("--port", type=int, default=8080)
    a.add_argument("--health", default="/healthz")
    for p in (a, s := sub.add_parser("sync", help="render, validate, apply, wait for health")):
        p.add_argument("--yes", action="store_true", help="don't ask")
        p.add_argument("--build", action="store_true", help="rebuild the images too")
        p.add_argument("--force", action="store_true", help="apply even if nothing changed")
    sub.add_parser("check", help="render and validate into generated/.next; change nothing")
    sub.add_parser("list", help="the apps, their sites and services")
    r = sub.add_parser("remove", help="stop an app (its files, data and logs stay)")
    r.add_argument("name")
    r.add_argument("--yes", action="store_true")
    r.set_defaults(build=False, force=True)
    args = ap.parse_args(argv)
    if args.cmd == "add":
        args.force = True
    try:
        return {"add": cmd_add, "sync": cmd_sync, "check": cmd_check, "list": cmd_list, "remove": cmd_remove}[args.cmd](args)
    except Problem as e:
        say(f"STOP: {e}")
        return 2
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
